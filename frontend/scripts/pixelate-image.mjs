#!/usr/bin/env node
/**
 * One-off dev tool — NOT part of the build. Downsamples a real source image to an N×N grid and
 * quantizes each cell to the nearest color in the jewel game's palette, writing a committed
 * `levels/levelN.ts` file consumed directly at runtime (no image processing happens in the app).
 *
 * Usage:
 *   node scripts/pixelate-image.mjs <inputImagePath> <outputLevelPath> [gridSize] [levelName]
 *
 * Example:
 *   node scripts/pixelate-image.mjs scripts/source-images/gem.png src/features/jewel/levels/level1.ts 8 "Gem"
 *
 * The palette hex values below must stay in sync with COLOR_HEX in
 * `src/features/jewel/config/constants.ts` — this script is intentionally dependency-free of the
 * app's TypeScript source so it can run as plain Node/ESM without a TS loader.
 */
import { Jimp, intToRGBA } from 'jimp';
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname } from 'node:path';

const PALETTE = {
  red: '#e2473b',
  blue: '#3b6fe2',
  green: '#3bbf6e',
  yellow: '#e2c53b',
  purple: '#9b3be2',
};

function hexToRgb(hex) {
  const n = parseInt(hex.replace('#', ''), 16);
  return { r: (n >> 16) & 0xff, g: (n >> 8) & 0xff, b: n & 0xff };
}

const PALETTE_RGB = Object.fromEntries(
  Object.entries(PALETTE).map(([name, hex]) => [name, hexToRgb(hex)]),
);

function nearestColorId(r, g, b) {
  let bestName = null;
  let bestDist = Infinity;
  for (const [name, rgb] of Object.entries(PALETTE_RGB)) {
    const dist = (r - rgb.r) ** 2 + (g - rgb.g) ** 2 + (b - rgb.b) ** 2;
    if (dist < bestDist) {
      bestDist = dist;
      bestName = name;
    }
  }
  return bestName;
}

async function main() {
  const [inputPath, outputPath, gridSizeArg, levelName] = process.argv.slice(2);

  if (!inputPath || !outputPath) {
    console.error('Usage: node scripts/pixelate-image.mjs <inputImagePath> <outputLevelPath> [gridSize] [levelName]');
    process.exit(1);
  }

  const gridSize = Number.parseInt(gridSizeArg ?? '8', 10);
  const name = levelName ?? 'Level';

  const image = await Jimp.read(inputPath);
  image.resize({ w: gridSize, h: gridSize });

  const targetColors = [];
  for (let row = 0; row < gridSize; row++) {
    const rowColors = [];
    for (let col = 0; col < gridSize; col++) {
      const pixel = intToRGBA(image.getPixelColor(col, row));
      rowColors.push(nearestColorId(pixel.r, pixel.g, pixel.b));
    }
    targetColors.push(rowColors);
  }

  const gridLiteral = targetColors
    .map((row) => `    [${row.map((c) => `'${c}'`).join(', ')}],`)
    .join('\n');

  const fileContent = `import { defineLevel } from './types';

// Generated by scripts/pixelate-image.mjs from ${JSON.stringify(inputPath)} at grid size ${gridSize}.
// Do not hand-edit targetColors — regenerate from the source image instead.
export const level: ReturnType<typeof defineLevel> = defineLevel({
  name: ${JSON.stringify(name)},
  targetColors: [
${gridLiteral}
  ],
});
`;

  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, fileContent, 'utf8');

  console.log(`Wrote ${gridSize}x${gridSize} level to ${outputPath}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
